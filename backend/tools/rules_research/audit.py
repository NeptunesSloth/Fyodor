def audit(rules: crmod.ComprehensiveRules) -> list[tuple[str, str, str, str]]:
    """(rule, status, note, rule text) for every SBA in the text, plus stale entries."""
    out = []
    in_text = [n for n in rules.rules if n[:5] in ("704.5", "704.6") and n not in ("704.5", "704.6")]
    for num in in_text:
        status, note = SBA.get(num, ("UNREVIEWED", "new or renumbered: review against the engine"))
        out.append((num, status, note, rules.rules[num].text.replace("\n", " ")))
    for num in SBA:
        if num not in rules.rules:
            out.append((num, "STALE", "no longer in the rules: remove or renumber", ""))
    return out


def markdown(rules: crmod.ComprehensiveRules) -> str:
    rows = audit(rules)
    counts: dict[str, int] = {}
    for _, status, _, _ in rows:
        counts[status] = counts.get(status, 0) + 1
    lines = [f"# State-based actions audit (Comprehensive Rules {rules.effective})", "",
             "Generated by `python -m tools.rules_research.audit` from the stored rules text.", "",
             " · ".join(f"{k}: {v}" for k, v in sorted(counts.items())), "",
             "| Rule | Status | Fyodor | Rule text |", "|---|---|---|---|"]
    for num, status, note, text in rows:
        short = text if len(text) <= 160 else text[:157] + "…"
        lines.append(f"| {num} | {status} | {note} | {short.replace('|', '/')} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = latest_text()
    if text is None:
        print("No rules stored yet: run python -m tools.rules_research.update", file=sys.stderr)
        return 1
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "sba_audit.md").write_text(markdown(crmod.parse(text)), "utf-8")
    print(f"wrote {REPORTS_DIR / 'sba_audit.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
